const BY_ID = new Map(OPPORTUNITIES.map((opportunity) => [opportunity.id, opportunity]));

export function opportunityById(id: string): Opportunity | undefined {
  return BY_ID.get(id);
}

export function opportunitiesByIds(ids: string[]): Opportunity[] {
  return ids
    .map((id) => BY_ID.get(id))
    .filter((opportunity): opportunity is Opportunity => Boolean(opportunity));
}
